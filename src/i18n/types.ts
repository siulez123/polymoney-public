export type Locale = "pt" | "en" | "es";

export const LOCALES: Locale[] = ["pt", "en", "es"];

export function parseLocale(raw?: string | null): Locale {
  if (!raw) return "pt";
  const s = raw.trim().toLowerCase().slice(0, 2);
  if (s === "en" || s === "es" || s === "pt") return s;
  return "pt";
}

